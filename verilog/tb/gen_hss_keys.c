// Writes rtl/hss_keys.svh: the test signers' public keys as the PUBKEYS
// parameter of hss_pkg. Run through `make hss-keys`. Each key is checked by
// signing and verifying with the reference implementation before it is
// emitted, so a key that comes out of here verifies against RFC 8554.

#include <stdio.h>
#include <string.h>
#include "hss_signer.h"

#define NUM_SIGNERS 2

static void hex(const unsigned char *p, int n)
{
    for (int i = 0; i < n; i++) printf("%02x", p[i]);
}

int main(void)
{
    unsigned char pub[NUM_SIGNERS][HSS_SIGNER_PUB_LEN];

    for (int s = 0; s < NUM_SIGNERS; s++) {
        if (hss_signer_pubkey(s, pub[s])) return 1;

        unsigned levels   = (pub[s][0] << 24) | (pub[s][1] << 16) | (pub[s][2]  << 8) | pub[s][3];
        unsigned lms_type = (pub[s][4] << 24) | (pub[s][5] << 16) | (pub[s][6]  << 8) | pub[s][7];
        unsigned ots_type = (pub[s][8] << 24) | (pub[s][9] << 16) | (pub[s][10] << 8) | pub[s][11];
        if (levels != HSS_SIGNER_LEVELS || lms_type != 0x5 || ots_type != 0x4) {
            fprintf(stderr, "signer %d: unexpected parameter set L=%u lms=%u ots=%u\n",
                    s, levels, lms_type, ots_type);
            return 1;
        }

        // Self-check: a signature from this key verifies with the reference
        unsigned char msg[32], sig[HSS_SIGNER_SIG_LEN];
        memset(msg, 0x5a + s, sizeof msg);
        if (hss_signer_sign(s, msg, sig) || hss_signer_verify(pub[s], msg, sig)) {
            fprintf(stderr, "signer %d: self-check signature did not verify\n", s);
            return 1;
        }
    }

    printf("// Generated by `make hss-keys` (tb/gen_hss_keys.c over hash-sigs) - do not edit.\n"
           "// The test signers' top-tree identities; tb/hss_signer.c holds the private keys.\n"
           "parameter pubkey_t PUBKEYS [%d] = '{\n", NUM_SIGNERS);
    for (int s = 0; s < NUM_SIGNERS; s++) {
        printf("    %d: '{l:            HSS_LEVELS,\n"
               "         lms_type:     LMS_TYPE,\n"
               "         otstype:      LMOTS_TYPE,\n", s);
        printf("         identifier:   128'h"); hex(pub[s] + 12, 16); printf(",\n");
        printf("         root_pub_key: 256'h"); hex(pub[s] + 28, 32);
        printf("}%s\n", s + 1 < NUM_SIGNERS ? "," : "");
    }
    printf("};\n");
    return 0;
}
