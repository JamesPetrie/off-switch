// Writes rtl/slh_keys.svh: the test signers' public keys as the SLH_KEYS
// parameter of slh_pkg. Run through `make slh-keys`. Each key is checked by
// signing and verifying with the reference implementation before it is
// emitted, so a key that comes out of here verifies against FIPS 205.

#include <stdio.h>
#include <string.h>
#include "slh_signer.h"

#define NUM_SIGNERS 2

static void hex(const unsigned char *p, int n)
{
    for (int i = 0; i < n; i++) printf("%02x", p[i]);
}

int main(void)
{
    static unsigned char pub[NUM_SIGNERS][SLH_SIGNER_PUB_LEN];
    static unsigned char sig[SLH_SIGNER_SIG_LEN];

    for (int s = 0; s < NUM_SIGNERS; s++) {
        if (slh_signer_pubkey(s, pub[s])) return 1;

        // Self-check: a signature from this key verifies with the reference
        unsigned char msg[32];
        memset(msg, 0x5a + s, sizeof msg);
        if (slh_signer_sign(s, msg, sig) || slh_signer_verify(pub[s], msg, sig)) {
            fprintf(stderr, "signer %d: self-check signature did not verify\n", s);
            return 1;
        }
    }

    printf("// Generated by `make slh-keys` (tb/gen_slh_keys.c over slhdsa-c) - do not edit.\n"
           "// The test signers' public keys; tb/slh_signer.c holds the private keys.\n"
           "localparam int unsigned SLH_NUM_KEYS = %d;\n"
           "localparam slh_key_t SLH_KEYS [SLH_NUM_KEYS] = '{\n", NUM_SIGNERS);
    for (int s = 0; s < NUM_SIGNERS; s++) {
        printf("    %d: '{seed: %d'h", s, 8 * SLH_SIGNER_N); hex(pub[s], SLH_SIGNER_N);
        printf(",\n         root: %d'h", 8 * SLH_SIGNER_N);   hex(pub[s] + SLH_SIGNER_N, SLH_SIGNER_N);
        printf("}%s\n", s + 1 < NUM_SIGNERS ? "," : "");
    }
    printf("};\n");
    return 0;
}
